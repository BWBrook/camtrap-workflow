#' Read and validate configuration
#'
#' @param path Path to config YAML.
#' @param attach_runtime Whether to attach a supported evidence-run context.
#' @return List with configuration values.
#' @export
read_config <- function(path = "config.yml", attach_runtime = TRUE) {
  import::from("fs", file_exists)
  import::from("yaml", read_yaml)

  if (!file_exists(path)) {
    stop("config.yml not found at path: ", path)
  }

  config <- read_yaml(path)
  config <- modifyList(default_config(), config)
  config <- validate_config(config)

  context_path <- Sys.getenv("CAMTRAP_EVIDENCE_CONTEXT", unset = "")
  if (isTRUE(attach_runtime) && nzchar(context_path)) {
    if (!exists("read_run_context", mode = "function") ||
          !exists("attach_evidence_context", mode = "function")) {
      stop("Evidence-run helpers must be loaded before reading runtime configuration.")
    }
    config <- attach_evidence_context(config, read_run_context(context_path))
  }
  config
}

validate_entity_config <- function(selection) {
  fields <- c(
    "profile_id",
    "sidecar_path",
    "sidecar_sha256",
    "authority_reference"
  )
  if (!is.list(selection) ||
        !identical(sort(names(selection)), sort(fields))) {
    stop(
      "config.yml entity_resolution must contain exactly profile_id, ",
      "sidecar_path, sidecar_sha256, and authority_reference."
    )
  }
  values <- selection[fields]
  nulls <- vapply(values, is.null, logical(1))
  if (all(nulls)) {
    return(invisible(TRUE))
  }
  if (any(nulls) ||
    !all(vapply(values, function(value) {
      is.character(value) && length(value) == 1L && nzchar(value)
    }, logical(1)))) {
    stop(
      "config.yml entity_resolution must be an exact null selection or a ",
      "complete selected profile."
    )
  }
  digest <- "553abada14493f3a5f0ae3c072523b6d5cc0d0c6a6c6480ca17a9e3331f2d8ec"
  approved <- list(
    profile_id = "judbury-entity-crosswalk/1.0.0-proposed",
    sidecar_sha256 = digest,
    authority_reference = paste0(
      "goal007-judbury-crosswalk-sha256-",
      digest
    )
  )
  if (!grepl("^[a-f0-9]{64}$", selection$sidecar_sha256) ||
        !identical(selection[names(approved)], approved)) {
    stop(
      "config.yml entity_resolution selection has no exact approved authority."
    )
  }
  invisible(TRUE)
}

#' Validate configuration values
#'
#' @param config List of configuration values.
#' @return config invisibly.
#' @export
validate_config <- function(config) {
  required_paths <- c(
    "schema_version_path",
    "run_id",
    "timezone",
    "timezone_fixed_offset_hours",
    "event_threshold_minutes",
    "input_mode",
    "camtrapdp_acquisition",
    "paths",
    "analysis",
    "spatial_map",
    "time_qc",
    "diel",
    "sensitivity",
    "detection_history",
    "occupancy",
    "traits",
    "camtrapdp_export"
  )

  missing <- setdiff(required_paths, names(config))
  if (length(missing) > 0) {
    stop("config.yml missing required field(s): ", paste(missing, collapse = ", "))
  }

  if (!is.numeric(config$event_threshold_minutes) || length(config$event_threshold_minutes) != 1) {
    stop("config.yml field event_threshold_minutes must be a single numeric value.")
  }

  if (!is.character(config$timezone) || length(config$timezone) != 1) {
    stop("config.yml field timezone must be a single character value.")
  }

  if (!is.null(config$timezone_fixed_offset_hours)) {
    if (!is.numeric(config$timezone_fixed_offset_hours) ||
          length(config$timezone_fixed_offset_hours) != 1) {
      stop("config.yml field timezone_fixed_offset_hours must be NULL or a single numeric value.")
    }
  }

  if (!is.character(config$run_id) || length(config$run_id) != 1) {
    stop("config.yml field run_id must be a single character value.")
  }

  if (!is.character(config$input_mode) || length(config$input_mode) != 1) {
    stop("config.yml field input_mode must be a single character value.")
  }

  if (!config$input_mode %in% c("four_table", "camtrapdp")) {
    stop("config.yml input_mode must be 'four_table' or 'camtrapdp'.")
  }

  acquisition <- config$camtrapdp_acquisition
  if (!is.list(acquisition) ||
        !is.character(acquisition$mode) ||
        length(acquisition$mode) != 1L ||
        !acquisition$mode %in% c("local", "remote")) {
    stop("config.yml camtrapdp_acquisition.mode must be 'local' or 'remote'.")
  }
  if (!is.character(acquisition$cache_dir) ||
        length(acquisition$cache_dir) != 1L ||
        !nzchar(acquisition$cache_dir)) {
    stop("config.yml camtrapdp_acquisition.cache_dir must be one non-empty path.")
  }
  if (!is.null(acquisition$descriptor_sha256) &&
        (!is.character(acquisition$descriptor_sha256) ||
           length(acquisition$descriptor_sha256) != 1L ||
           !grepl("^[A-Fa-f0-9]{64}$", acquisition$descriptor_sha256))) {
    stop("config.yml camtrapdp_acquisition.descriptor_sha256 must be NULL or one SHA-256 digest.")
  }
  if (!is.list(acquisition$resource_sha256)) {
    stop("config.yml camtrapdp_acquisition.resource_sha256 must be a named map.")
  }

  analysis_fields <- c("rarefaction", "report")
  missing_analysis <- setdiff(analysis_fields, names(config$analysis))
  if (length(missing_analysis) > 0) {
    stop("config.yml missing analysis field(s): ", paste(missing_analysis, collapse = ", "))
  }

  for (field in analysis_fields) {
    if (!is.logical(config$analysis[[field]]) || length(config$analysis[[field]]) != 1) {
      stop("config.yml analysis.", field, " must be TRUE/FALSE.")
    }
  }

  if (isTRUE(config$analysis$report) && !isTRUE(config$analysis$rarefaction)) {
    stop("config.yml analysis.rarefaction must be TRUE when analysis.report is TRUE.")
  }

  if (!is.list(config$spatial_map) || is.null(config$spatial_map$enable)) {
    stop("config.yml spatial_map.enable must be provided.")
  }

  if (!is.logical(config$spatial_map$enable) || length(config$spatial_map$enable) != 1) {
    stop("config.yml spatial_map.enable must be TRUE/FALSE.")
  }

  if (!is.null(config$spatial_map$surface_var)) {
    if (!is.character(config$spatial_map$surface_var) ||
          length(config$spatial_map$surface_var) != 1) {
      stop("config.yml spatial_map.surface_var must be NULL or a single character value.")
    }
  }

  if (!is.numeric(config$spatial_map$resolution) ||
        length(config$spatial_map$resolution) != 1) {
    stop("config.yml spatial_map.resolution must be a single numeric value.")
  }

  if (!is.numeric(config$spatial_map$buffer_deg) ||
        length(config$spatial_map$buffer_deg) != 1) {
    stop("config.yml spatial_map.buffer_deg must be a single numeric value.")
  }

  if (!is.numeric(config$spatial_map$buffer_frac) ||
        length(config$spatial_map$buffer_frac) != 1) {
    stop("config.yml spatial_map.buffer_frac must be a single numeric value.")
  }

  if (!is.logical(config$spatial_map$label_sites) ||
        length(config$spatial_map$label_sites) != 1) {
    stop("config.yml spatial_map.label_sites must be TRUE/FALSE.")
  }

  if (!is.numeric(config$spatial_map$label_size) ||
        length(config$spatial_map$label_size) != 1) {
    stop("config.yml spatial_map.label_size must be a single numeric value.")
  }

  if (!is.numeric(config$spatial_map$label_nudge_frac) ||
        length(config$spatial_map$label_nudge_frac) != 1) {
    stop("config.yml spatial_map.label_nudge_frac must be a single numeric value.")
  }

  if (!is.logical(config$spatial_map$show_north_arrow) ||
        length(config$spatial_map$show_north_arrow) != 1) {
    stop("config.yml spatial_map.show_north_arrow must be TRUE/FALSE.")
  }

  if (!is.logical(config$spatial_map$show_scale_bar) ||
        length(config$spatial_map$show_scale_bar) != 1) {
    stop("config.yml spatial_map.show_scale_bar must be TRUE/FALSE.")
  }

  if (!is.numeric(config$spatial_map$scale_bar_km) ||
        length(config$spatial_map$scale_bar_km) != 1) {
    stop("config.yml spatial_map.scale_bar_km must be a single numeric value.")
  }

  if (!is.list(config$time_qc) || is.null(config$time_qc$backward_jump_threshold_hours)) {
    stop("config.yml time_qc.backward_jump_threshold_hours must be provided.")
  }

  if (!is.numeric(config$time_qc$backward_jump_threshold_hours) ||
        length(config$time_qc$backward_jump_threshold_hours) != 1) {
    stop("config.yml time_qc.backward_jump_threshold_hours must be a single numeric value.")
  }

  if (!is.list(config$diel) || is.null(config$diel$method)) {
    stop("config.yml diel.method must be provided.")
  }

  if (!config$diel$method %in% c("flash", "clock")) {
    stop("config.yml diel.method must be 'flash' or 'clock'.")
  }

  if (is.null(config$diel$day_start_hour) || is.null(config$diel$day_end_hour)) {
    stop("config.yml diel.day_start_hour and diel.day_end_hour must be provided.")
  }

  if (!is.numeric(config$diel$day_start_hour) || !is.numeric(config$diel$day_end_hour) ||
        length(config$diel$day_start_hour) != 1 || length(config$diel$day_end_hour) != 1) {
    stop("config.yml diel.day_start_hour and diel.day_end_hour must be single numeric values.")
  }

  if (config$diel$day_start_hour < 0 || config$diel$day_start_hour > 23 ||
        config$diel$day_end_hour < 0 || config$diel$day_end_hour > 23 ||
        config$diel$day_end_hour <= config$diel$day_start_hour) {
    stop("config.yml diel.day_start_hour/day_end_hour must be within 0-23 and end > start.")
  }

  if (!is.list(config$sensitivity) || is.null(config$sensitivity$event_threshold_minutes)) {
    stop("config.yml sensitivity.event_threshold_minutes must be provided.")
  }

  if (!is.numeric(config$sensitivity$event_threshold_minutes) ||
        length(config$sensitivity$event_threshold_minutes) < 1) {
    stop("config.yml sensitivity.event_threshold_minutes must be a numeric vector.")
  }

  if (is.null(config$sensitivity$occasion_length_days) ||
        !is.numeric(config$sensitivity$occasion_length_days) ||
        length(config$sensitivity$occasion_length_days) < 1) {
    stop("config.yml sensitivity.occasion_length_days must be a numeric vector.")
  }

  if (!is.list(config$detection_history) || is.null(config$detection_history$occasion_length_days)) {
    stop("config.yml detection_history.occasion_length_days must be provided.")
  }

  if (!is.numeric(config$detection_history$occasion_length_days) ||
        length(config$detection_history$occasion_length_days) != 1 ||
        config$detection_history$occasion_length_days < 1) {
    stop("config.yml detection_history.occasion_length_days must be a positive integer.")
  }

  if (!is.list(config$occupancy)) {
    stop("config.yml occupancy must be provided as a list.")
  }

  if (config$input_mode == "camtrapdp") {
    camtrap_path <- config$paths$inputs$camtrapdp
    if (is.null(camtrap_path) || !is.character(camtrap_path) || !nzchar(camtrap_path)) {
      stop("config.yml paths.inputs.camtrapdp must be a non-empty string when input_mode = 'camtrapdp'.")
    }
    is_remote <- grepl("^https?://", camtrap_path, ignore.case = TRUE)
    if (identical(acquisition$mode, "remote") && !is_remote) {
      stop("Remote CamtrapDP acquisition requires an HTTP(S) descriptor URL.")
    }
    if (identical(acquisition$mode, "local") && is_remote) {
      stop("Local CamtrapDP acquisition requires a local descriptor path.")
    }
    if (identical(acquisition$mode, "remote") && is.null(acquisition$descriptor_sha256)) {
      stop("Remote CamtrapDP acquisition requires descriptor_sha256.")
    }
  }

  if (!is.null(config$validation)) {
    if (!is.list(config$validation) ||
          !identical(names(config$validation), "repair_decisions")) {
      stop(
        "config.yml validation must contain only the provisional ",
        "repair_decisions list."
      )
    }
    decisions <- config$validation$repair_decisions
    if (!is.list(decisions)) {
      stop("config.yml validation.repair_decisions must be an exact list.")
    }
    allowed_decision_fields <- c(
      "proposal_id",
      "proposal_digest",
      "decision",
      "reason"
    )
    for (decision in decisions) {
      required_decision_fields <- c(
        "proposal_id",
        "proposal_digest",
        "decision"
      )
      exact_fields <- is.list(decision) &&
        all(required_decision_fields %in% names(decision)) &&
        length(setdiff(names(decision), allowed_decision_fields)) == 0L
      if (!exact_fields) {
        stop(
          "config.yml repair decisions require exact proposal_id, ",
          "proposal_digest, decision, and optional reason fields."
        )
      }
      if (!is.character(decision$proposal_id) ||
            length(decision$proposal_id) != 1L ||
            !grepl("^[a-f0-9]{64}$", decision$proposal_id) ||
            !is.character(decision$proposal_digest) ||
            length(decision$proposal_digest) != 1L ||
            !grepl("^[a-f0-9]{64}$", decision$proposal_digest) ||
            !is.character(decision$decision) ||
            length(decision$decision) != 1L ||
            !decision$decision %in% c("approved", "declined")) {
        stop("config.yml repair decision fields are malformed.")
      }
      valid_reason <- is.null(decision$reason) ||
        is.character(decision$reason) && length(decision$reason) == 1L
      if (!valid_reason) {
        stop("config.yml repair decision reason must be one string or null.")
      }
    }
  }

  if (!is.null(config$entity_resolution)) {
    validate_entity_config(config$entity_resolution)
    selected_entity_profile <- !is.null(
      config$entity_resolution$profile_id
    )
    if (selected_entity_profile &&
          !identical(config$input_mode, "four_table")) {
      stop(
        "The approved Judbury entity-resolution profile is only valid ",
        "when input_mode = 'four_table'; CamtrapDP requires an explicit ",
        "null entity_resolution selection."
      )
    }
  }

  if (!is.null(config$occupancy$species) &&
        !is.character(config$occupancy$species)) {
    stop("config.yml occupancy.species must be NULL or a character vector.")
  }

  if (is.null(config$occupancy$top_n) ||
        !is.numeric(config$occupancy$top_n) ||
        length(config$occupancy$top_n) != 1 ||
        config$occupancy$top_n < 1) {
    stop("config.yml occupancy.top_n must be a positive integer.")
  }

  if (is.null(config$occupancy$covariates) ||
        !is.character(config$occupancy$covariates) ||
        length(config$occupancy$covariates) < 1) {
    stop("config.yml occupancy.covariates must be a character vector.")
  }

  if (!is.list(config$traits)) {
    stop("config.yml traits must be provided as a list.")
  }

  if (!is.list(config$camtrapdp_export)) {
    stop("config.yml camtrapdp_export must be provided as a list.")
  }

  if (!is.logical(config$camtrapdp_export$enable) || length(config$camtrapdp_export$enable) != 1) {
    stop("config.yml camtrapdp_export.enable must be TRUE/FALSE.")
  }

  required_export_fields <- c("name", "title", "description", "version", "license")
  missing_export <- setdiff(required_export_fields, names(config$camtrapdp_export))
  if (length(missing_export) > 0) {
    stop("config.yml camtrapdp_export missing field(s): ", paste(missing_export, collapse = ", "))
  }

  for (field in required_export_fields) {
    if (!is.character(config$camtrapdp_export[[field]]) || length(config$camtrapdp_export[[field]]) != 1) {
      stop("config.yml camtrapdp_export.", field, " must be a single character value.")
    }
  }

  if (is.null(config$traits$species_column) ||
        !is.character(config$traits$species_column) ||
        length(config$traits$species_column) != 1) {
    stop("config.yml traits.species_column must be a single character value.")
  }

  if (is.null(config$traits$columns) ||
        !is.character(config$traits$columns) ||
        length(config$traits$columns) < 1) {
    stop("config.yml traits.columns must be a character vector.")
  }

  if (!is.null(config$traits$association_traits) &&
        !is.character(config$traits$association_traits)) {
    stop("config.yml traits.association_traits must be NULL or a character vector.")
  }

  if (is.null(config$traits$environment_vars) ||
        !is.character(config$traits$environment_vars) ||
        length(config$traits$environment_vars) < 1) {
    stop("config.yml traits.environment_vars must be a character vector.")
  }

  invisible(config)
}

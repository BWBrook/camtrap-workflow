# data_dictionary.R
# Utilities for parsing and exporting the project data dictionary.

#' Parse `data_dictionary.md` into a canonical data frame
#'
#' The markdown file is structured as a set of sections (one per CSV file),
#' each containing a markdown table describing columns and meanings.
#'
#' @param md_path Path to `data_dictionary.md`.
#' @return A data frame with columns: file, Column, Type, Units_or_levels, Description
#'   (sorted by file, Column). Placeholder rows ("…") are removed.
#' @export
read_data_dictionary_md <- function(md_path) {
  import::from("readr", read_lines, read_delim, cols)
  import::from("dplyr", bind_rows, mutate, arrange, across, everything, filter, if_any)
  import::from("stringr", str_detect, str_match, str_trim)
  import::from("fs", file_exists)

  if (!file_exists(md_path)) {
    stop("data_dictionary.md not found at path: ", md_path)
  }

  parse_md_tables <- function(lines) {
    out <- list()
    current_file <- NULL
    buf <- character()

    for (ln in lines) {
      # Detect section header of the form "## n filename.csv"
      if (str_detect(ln, "^##\\s+[0-9]+\\s+")) {
        if (length(buf) > 0 && !is.null(current_file)) {
          out[[current_file]] <- paste(buf, collapse = "\n")
          buf <- character()
        }
        current_file <- str_match(ln, "##\\s+[0-9]+\\s+(\\S+\\.csv)")[, 2]
        next
      }

      if (str_detect(ln, "^\\|")) {
        buf <- c(buf, ln)
      }
    }

    if (length(buf) > 0 && !is.null(current_file)) {
      out[[current_file]] <- paste(buf, collapse = "\n")
    }

    out
  }

  md_lines <- read_lines(md_path)
  tbl_texts <- parse_md_tables(md_lines)

  dict_df <- bind_rows(lapply(names(tbl_texts), function(file) {
    df <- read_delim(
      I(tbl_texts[[file]]),
      delim = "|",
      trim_ws = TRUE,
      skip = 1,
      comment = "",
      show_col_types = FALSE,
      name_repair = "minimal",
      col_types = cols(.default = "c")
    )

    # Drop empty boundary columns created by markdown table pipes.
    bad_cols <- which(names(df) == "" | grepl("^\\.\\.\\.", names(df)))
    if (length(bad_cols) > 0) {
      df <- df[, -bad_cols, drop = FALSE]
    }

    if (ncol(df) < 4) {
      stop("Malformed markdown table for ", file, ": expected at least 4 columns.")
    }

    df <- df[, 1:4, drop = FALSE]
    colnames(df) <- c("Column", "Type", "Units_or_levels", "Description")

    mutate(df, file = file, .before = 1)
  }))

  dict_df |>
    mutate(across(everything(), \(x) str_trim(x))) |>
    filter(!if_any(everything(), \(x) x == "…")) |>
    arrange(file, Column)
}

#' Write a canonical data dictionary CSV
#'
#' @param dict_df A data frame from `read_data_dictionary_md()`.
#' @param csv_path Output path for `data_dictionary.csv`.
#' @return Invisibly returns `csv_path`.
#' @export
write_data_dictionary_csv <- function(dict_df, csv_path) {
  import::from("readr", write_csv, write_lines)

  csv_header <- "# This file is autogenerated from data_dictionary.md; DO NOT EDIT BY HAND."

  write_lines(csv_header, csv_path)
  write_csv(dict_df, csv_path, na = "", append = TRUE, col_names = TRUE)

  invisible(csv_path)
}
